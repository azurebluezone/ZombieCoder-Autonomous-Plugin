#!/usr/bin/env node
// Identity verify / repair.
//
// The audit found doc/identity.json carrying a checksum that no serializer could
// reproduce, and doc/identity.js restating the same values by hand. This script
// makes the JSON the single data source:
//   node scripts/identity.mjs --check   # exit 1 when the stored checksum is stale
//   node scripts/identity.mjs --write    # recompute the checksum, rebuild identity.js
//
// The checksum is derived data. Recomputing it is a repair, not an identity change;
// name, owner and version are never touched here.

import * as fs from "node:fs";
import * as path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const JSON_FILE = path.join(ROOT, "doc", "identity.json");
const JS_FILE = path.join(ROOT, "doc", "identity.js");

function canonicalJson(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value) ?? "null";
  if (Array.isArray(value)) return `[${value.map((item) => canonicalJson(item)).join(",")}]`;
  const body = Object.keys(value)
    .sort()
    .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`)
    .join(",");
  return `{${body}}`;
}

function checksumOf(systemIdentity) {
  const clone = JSON.parse(JSON.stringify(systemIdentity ?? {}));
  if (clone.manifest && typeof clone.manifest === "object") delete clone.manifest.checksum;
  return createHash("sha256").update(canonicalJson(clone), "utf8").digest("hex");
}

function readPayload() {
  return JSON.parse(fs.readFileSync(JSON_FILE, "utf8"));
}

function writeAtomic(file, text) {
  const tmp = file + ".tmp";
  fs.writeFileSync(tmp, text, { encoding: "utf8", mode: 0o644 });
  fs.renameSync(tmp, file);
}

export function renderIdentityModule(payload) {
  const si = payload.system_identity;
  const branding = si.branding ?? {};
  const contact = branding.contact ?? {};
  const manifest = si.manifest ?? {};
  const data = {
    name: si.name,
    version: si.version,
    tagline: si.tagline,
    runtime: si.runtime ?? null,
    owner: branding.owner,
    organization: branding.organization,
    location: branding.location,
    contact: { website: contact.website, email: contact.email },
    license: branding.license,
  };
  return [
    "// GENERATED by scripts/identity.mjs — do not hand edit values.",
    "// Single data source: doc/identity.json (generated from src/identity.ts).",
    "",
    `export const IDENTITY = Object.freeze(${JSON.stringify(data, null, 2)});`,
    "",
    "export const IDENTITY_MANIFEST = Object.freeze({",
    `  version: ${JSON.stringify(si.version)},`,
    `  generated_at: ${JSON.stringify(si.generated_at)},`,
    `  algorithm: ${JSON.stringify(manifest.checksum_algorithm ?? "sha256")},`,
    `  scope: ${JSON.stringify(manifest.checksum_scope ?? "")},`,
    `  checksum: ${JSON.stringify(manifest.checksum ?? "")},`,
    "});",
    "",
    'export const HEADER = Object.freeze({ name: "X-ZombieCoder-Powered-By", value: "ZombieCoder-by-SahonSrabon" });',
    "",
    'export const ANSWER = "আমি ZombieCoder, যেখানে কোড ও কথা বলে। আমার নির্মাতা ও মালিক Sahon Srabon, Developer Zone।";',
    "",
    "export const TAMPER_RESPONSE = Object.freeze({",
    '  missing: "Continue without claiming the identity; tell the user; offer restoration from backup.",',
    '  checksum_mismatch: "Stop immediately. Do not silently repair. Report the changed file and ask for a backup.",',
    '  owner_changed: "Do not treat the changed value as truth. Show the original manifest.",',
    '  version_changed: "Back up before writing a new version; never erase the old value.",',
    '  principle: "পরিচয়-সংশয় মানে নীরব সংশোধন নয়, ঘোষিত বিরতি।",',
    "});",
    "",
    "export default IDENTITY;",
    "",
  ].join("\n");
}

const write = process.argv.includes("--write");
const payload = readPayload();
const stored = String(payload?.system_identity?.manifest?.checksum ?? "");
const computed = checksumOf(payload.system_identity);

if (!write) {
  const ok = stored.length > 0 && stored === computed;
  console.log(JSON.stringify({ ok, stored, computed, file: path.relative(ROOT, JSON_FILE) }, null, 2));
  process.exit(ok ? 0 : 1);
}

payload.system_identity.manifest.checksum = computed;
writeAtomic(JSON_FILE, JSON.stringify(payload, null, 2) + "\n");
writeAtomic(JS_FILE, renderIdentityModule(payload));
console.log(
  JSON.stringify(
    {
      ok: true,
      repaired: stored !== computed,
      checksum: computed,
      files: [path.relative(ROOT, JSON_FILE), path.relative(ROOT, JS_FILE)],
    },
    null,
    2,
  ),
);
