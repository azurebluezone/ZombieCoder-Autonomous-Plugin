// ZombieCoder — documentation generator entry point.
//
// Usage:
//   node src/generate.ts [--out <dir>]
//
// The .ts files ARE the source of truth. This script writes the markdown.
// Nothing is overwritten silently: existing files are copied to a timestamped
// backup before writing, and writes are atomic (temp -> rename).

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { renderIdentity, identityPayload } from "./identity.ts";
import { renderAgents } from "./agents.ts";
import { renderEthics } from "./ethics.ts";
import { renderRuntime } from "./runtime.ts";
import { DEFAULT_OPENCODE_API_URL } from "./zombie/defaults.ts";

const HERE = import.meta.dirname;
const ROOT = path.resolve(HERE, "..");

function arg(name: string, fallback: string): string {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const OUT = path.resolve(arg("--out", path.join(ROOT, "doc")));
const generatedAt = new Date().toISOString();

// The runtime version is read from the live server, never invented.
async function readRuntimeVersion(): Promise<{ version: string; source: string }> {
  const fallback = { version: "UNKNOWN", source: "runtime probe unavailable" };
  try {
    const configRoot = process.env.XDG_CONFIG_HOME
      ? path.join(process.env.XDG_CONFIG_HOME, "opencode")
      : path.join(os.homedir(), ".config", "opencode");
    const configPath = path.join(configRoot, "service.json");
    if (!fs.existsSync(configPath)) return fallback;
    const password = JSON.parse(fs.readFileSync(configPath, "utf8")).password;
    if (!password) return fallback;
    const base = DEFAULT_OPENCODE_API_URL;
    const res = await fetch(base + "/api/info", {
      headers: { Authorization: "Basic " + Buffer.from("opencode:" + password).toString("base64") },
      signal: AbortSignal.timeout(5000),
    });
    if (!res.ok) return fallback;
    const info = await res.json();
    return { version: String(info.version ?? "UNKNOWN"), source: "GET /api/info (observed at generation time)" };
  } catch {
    return fallback;
  }
}

function sha256(text: string): string {
  return crypto.createHash("sha256").update(text, "utf8").digest("hex");
}

function backupExisting(file: string, stamp: string): string | null {
  if (!fs.existsSync(file)) return null;
  const dir = path.join(ROOT, ".backups", stamp);
  fs.mkdirSync(dir, { recursive: true });
  const target = path.join(dir, path.basename(file));
  fs.copyFileSync(file, target);
  return path.relative(ROOT, target);
}

function writeAtomic(file: string, content: string): void {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = file + ".zombiecoder-tmp";
  fs.writeFileSync(tmp, content, { encoding: "utf8", mode: 0o644 });
  fs.renameSync(tmp, file);
}

function footer(
  stamp: string,
  branding: { owner: string; organization: string; location: string; license: string },
): string {
  return [
    "",
    "---",
    "",
    "**ZombieCoder** — যেখানে কোড ও কথা বলে",
    "",
    "- Generated by: `zombiecoder-docs-generator`",
    "- Generated at: " + stamp,
    "- Source of truth: `src/*.ts` (this markdown is a build artifact)",
    `- Owner: ${branding.owner} (${branding.organization}), ${branding.location}`,
    `- License: ${branding.license}`,
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  const stamp = generatedAt.replace(/[:.]/g, "-");
  const rt = await readRuntimeVersion();
  // The product version and the live runtime build are different facts. Keeping
  // them in one field made every OpenCode upgrade look like an identity change.
  const productVersion = String(
    JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8")).version ?? "0.0.0",
  );
  const identityCtx = {
    generatedAt,
    version: productVersion,
    versionSource: "package.json",
    runtime: rt,
  };
  const identity = identityPayload(identityCtx);

  const docs: { name: string; body: string }[] = [
    { name: "Identity Specification.md", body: renderIdentity(identityCtx) },
    { name: "Agent Architecture.md", body: renderAgents() },
    { name: "Persona & Ethics.md", body: renderEthics() },
    { name: "Runtime Operations.md", body: renderRuntime() },
  ];

  const report: string[] = [];
  report.push("target : " + OUT);
  report.push("product: " + productVersion + "  (package.json)");
  report.push("runtime: " + rt.version + "  (" + rt.source + ")");
  report.push("");

  for (const doc of docs) {
    const file = path.join(OUT, doc.name);
    const backed = backupExisting(file, stamp);
    const content = doc.body + footer(generatedAt, identity.system_identity.branding);
    writeAtomic(file, content);
    report.push(
      "  " + doc.name.padEnd(30) +
      String(Buffer.byteLength(content, "utf8")).padStart(8) + " B  " +
      String(content.split("\n").length).padStart(5) + " lines  " +
      "sha256:" + sha256(content).slice(0, 12) +
      (backed ? "   backup: " + backed : "   backup: (new file)")
    );
  }

  // identity.json — the machine-readable DNA, checksummed over its own payload.
  // The checksum MUST come from identityChecksum() (canonical JSON, checksum
  // field removed). Hashing JSON.stringify(payload) here produced a digest that
  // no verifier could reproduce, because key order was incidental.
  const payload = identity;
  const withChecksum = payload;
  const identityFile = path.join(OUT, "identity.json");
  const identityBacked = backupExisting(identityFile, stamp);
  const identityText = JSON.stringify(withChecksum, null, 2) + "\n";
  writeAtomic(identityFile, identityText);
  report.push(
    "  " + "identity.json".padEnd(30) +
    String(Buffer.byteLength(identityText, "utf8")).padStart(8) + " B  " +
    "checksum:" + withChecksum.system_identity.manifest.checksum.slice(0, 12) +
    (identityBacked ? "   backup: " + identityBacked : "   backup: (new file)")
  );

  console.log("ZombieCoder doc generator");
  for (const line of report) console.log(line);
}

await main();
